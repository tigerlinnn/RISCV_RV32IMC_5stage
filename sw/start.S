// ============================================================================
// start.S — RISCV_1 上的启动代码（CoreMark 用）
// ----------------------------------------------------------------------------
// 硬件复位后 PC = 0，所以这段必须排在存储器最前面（链接脚本把它放在 .text.init）。
// 它干四件事：
//   1. 设栈指针 sp        （C 语言没有栈就跑不了）
//   2. 把 .bss 清零       （未初始化的全局变量必须从 0 开始；
//                          我们的存储器出厂预填的是 NOP=0x13，不是 0）
//   3. 设 mtvec           （异常/中断的入口）
//   4. 跳到 main
//
// 注意：不需要搬 .data —— 我们的存储器就是那份 .hex，.data 的初值
//       在 objcopy 打 hex 的时候已经一起装进去了，上电就在它该在的地址上。
// ============================================================================

    .section .text.init
    .globl  _start
    .type   _start, @function
_start:
    // ---- 1. 设栈指针：_stack_top 这个符号由链接脚本 board.ld 定义 ----
    la      sp, _stack_top

    // ---- 2. 清 .bss：__bss_start / __bss_end 也来自链接脚本 ----
    la      t0, __bss_start
    la      t1, __bss_end
1:
    bgeu    t0, t1, 2f          // 起点 >= 终点 -> 清完了
    sw      zero, 0(t0)         // 一个字（4 字节）写 0
    addi    t0, t0, 4
    j       1b
2:

    // ---- 3. 设陷阱入口 ----
    la      t0, trap_handler
    csrw    mtvec, t0

    // ---- 4. 进入 C 的世界 ----
    call    main

    // main 正常不会返回；万一返回了，绝不能让它继续往下跑。
3:
    j       3b

// ----------------------------------------------------------------------------
// 陷阱处理程序。
//   CoreMark 理论上不应该触发任何异常。如果触发了，说明程序已经错了 ——
//   死循环停在这里，比让它乱跑好定位得多（可以挂 ILA 看 PC）。
// ----------------------------------------------------------------------------
    .align 4
    .globl  trap_handler
    .type   trap_handler, @function
trap_handler:
    j       trap_handler

    .size   _start, . - _start
