#!/usr/bin/env python3
"""Generate synthetic single-layer vectors + bit-exact golden model.

Usage:
    python gen_vectors.py probe1|probe2|A|B [outdir]

The accelerator is a single 8-input-channel x 8-output-channel 3x3 conv
engine.  Keep all test values small so the 18-bit accumulator never wraps;
then exact integer arithmetic matches the RTL's adder tree bit-for-bit.
"""
import json
import os
import random
import sys

CONV_COL = {0: 15, 1: 28, 2: 54, 3: 106, 4: 210, 5: 418}


def int8(x):
    x &= 0xFF
    return x - 256 if x >= 128 else x


def wrap8(x):
    return int8(x)


def sat16(x):
    return max(-32768, min(32767, x))


def sat8(x):
    return max(-128, min(127, x))


def quantize(acc, scale, shift, zp_out):
    v = sat16(acc)
    prod = v * scale
    shifted = prod >> (15 + shift)          # Python >> is arithmetic
    rnd = (prod >> (14 + shift)) & 1
    q = sat8(shifted + rnd)
    return (q + zp_out) & 0xFF


def activate(q, relu_type, zp_out, lut):
    if relu_type:
        return q if int8(q) >= int8(zp_out) else (zp_out & 0xFF)
    return lut[q] & 0xFF


def pack_beats(beats):
    words = []
    for beat in beats:
        w = 0
        for i, b in enumerate(beat):
            w |= (b & 0xFF) << (8 * i)
        words.append(w)
    return words


def write_hex(path, words, width=16):
    with open(path, "w") as f:
        for w in words:
            f.write(("%0*X" % (width, w & ((1 << (4 * width)) - 1))) + "\n")


def beat_checksum(words):
    """djb2-style 32-bit checksum over 64-bit beats; mirrored in yolo_main.c."""
    h = 5381
    for w in words:
        h = (h * 33) ^ (w & 0xFFFFFFFF) ^ ((w >> 32) & 0xFFFFFFFF)
        h &= 0xFFFFFFFF
    return h


def write_c_header(path, name, cfg, ifm_words, wgt_words, bia_words,
                   lut_words, gold_words):
    def arr(name, ctype, words):
        lines = ["static const %s %s[%d] = {" % (ctype, name, len(words))]
        for i in range(0, len(words), 4):
            chunk = ", ".join("0x%016Xull" % w if ctype == "uint64_t"
                              else "0x%08Xu" % w
                              for w in words[i:i + 4])
            lines.append("    " + chunk + ",")
        lines.append("};")
        return "\n".join(lines)

    text = f"""// Auto-generated by tools/gen_vectors.py -- do not edit.
#ifndef YOLO_VECTORS_H
#define YOLO_VECTORS_H
#include <stdint.h>

#define YOLO_CASE_NAME  "{name}"
#define YOLO_ROW        {cfg.row}
#define YOLO_SEL        {cfg.sel}
#define YOLO_POOL       {cfg.pool}
#define YOLO_STRIDE     {cfg.stride}
#define YOLO_RELU       {cfg.relu_type}
#define YOLO_FIRST      {cfg.first}
#define YOLO_LAST       {cfg.last}
#define YOLO_IFMSEL     1
#define YOLO_SCALE      0x{cfg.scale:04X}
#define YOLO_SHIFT      {cfg.shift}
#define YOLO_ZP_IN      {cfg.zp_in}
#define YOLO_ZP_OUT     {cfg.zp_out}
#define YOLO_ZP_ACT     {cfg.zp_act}

#define YOLO_IFM_BEATS  {len(ifm_words)}
#define YOLO_WGT_BEATS  {len(wgt_words)}
#define YOLO_BIA_BEATS  {len(bia_words)}
#define YOLO_LUT_BEATS  {len(lut_words)}
#define YOLO_GOLD_BEATS {len(gold_words)}
#define YOLO_GOLD_CHK   0x{beat_checksum(gold_words):08X}u

{arr("yolo_lut", "uint64_t", lut_words)}

{arr("yolo_bias", "uint64_t", bia_words)}

{arr("yolo_wgt", "uint64_t", wgt_words)}

{arr("yolo_ifm", "uint64_t", ifm_words)}

#endif  // YOLO_VECTORS_H
"""
    with open(path, "w") as f:
        f.write(text)


class Layer:
    def __init__(self, name, sel, row, scale, shift, zp_in, zp_out,
                 zp_act, relu_type, pool, stride, first, last):
        self.name = name
        self.sel = sel
        self.row = row
        self.conv_col = CONV_COL[sel]
        self.scale = scale
        self.shift = shift
        self.zp_in = zp_in
        self.zp_out = zp_out
        self.zp_act = zp_act
        self.relu_type = relu_type
        self.pool = pool
        self.stride = stride
        self.first = first
        self.last = last
        self.out_groups = 1

    def reg0_static(self, ifmbuf_sel):
        return ((self.row << 24) | (self.sel << 10) | (self.pool << 5) |
                (self.stride << 15) | (self.relu_type << 16) |
                (self.first << 6) | (self.last << 7) | (ifmbuf_sel << 8))

    def reg1(self):
        return (self.scale & 0xFFFF) | ((self.shift & 0xF) << 16)

    def reg2(self):
        return ((self.zp_in & 0xFF) | ((self.zp_out & 0xFF) << 8) |
                ((self.zp_act & 0xFF) << 16))

    def ctrl_words(self, gold_beats=0):
        static = self.reg0_static(1)
        return [
            0x209, 0x008,   # LUT stream (axis_buf_sel=2)
            0x20D, 0x00C,   # bias stream (axis_buf_sel=3)
            0x205, 0x004,   # weight stream (axis_buf_sel=1)
            0x201, 0x000,   # IFM stream (axis_buf_sel=0, ifmbuf_sel=0)
            static | 0x210, static,      # conv task / static
            static | 0x202, static,      # send task / static
            self.reg1(), self.reg2(), 0x0000_0000,
            256, 8, 72, self.row * self.conv_col, gold_beats,
        ]


def make_identity_weights():
    w = [[[[0] * 8 for _ in range(9)] for _ in range(8)]]
    for ic in range(8):
        w[0][ic][4][ic] = 1          # center tap, out-ch == in-ch
    return w


def golden_conv(ifm, w, bias, cfg):
    """Full OFM grid as the accelerator emits it (row x conv_col beats).

    The core sends a 1-pixel zero border around the valid interior.  Interior
    cell (r,c), r/c in 1..dim-2, is the conv of the window whose top-left is
    IFM(r-1,c-1) -- i.e. byte lane t of the 72-bit weight window is tap t.
    """
    rows, cols, _ = len(ifm), len(ifm[0]), 8
    # Border pixels still go through quant+activation with a zeroed
    # accumulator, so they carry the activation of zero (== zp_out for ReLU),
    # not a hard zero.
    border = activate(quantize(0, cfg.scale, cfg.shift, cfg.zp_out),
                      cfg.relu_type, cfg.zp_out, cfg.lut)
    out = []
    for og in range(cfg.out_groups):
        for r in range(rows):
            for c in range(cols):
                if r == 0 or r == rows - 1 or c == 0 or c == cols - 1:
                    out.append([border] * 8)
                    continue
                beat = []
                for oc in range(8):
                    acc = 0
                    for ic in range(8):
                        for tap in range(9):
                            dr, dc = divmod(tap, 3)
                            qin = wrap8(ifm[r - 1 + dr][c - 1 + dc][ic] -
                                        cfg.zp_in)
                            acc += qin * w[og][ic][tap][oc]
                    if cfg.last:
                        acc += bias[og * 8 + oc]
                    q = quantize(acc, cfg.scale, cfg.shift, cfg.zp_out)
                    beat.append(activate(q, cfg.relu_type, cfg.zp_out, cfg.lut))
                out.append(beat)
    return out


def build_case(name, outdir):
    random.seed(1234)
    if name == "probe1":
        cfg = Layer("probe1", sel=0, row=6, scale=0x7FFF, shift=0,
                    zp_in=0, zp_out=0, zp_act=0, relu_type=1,
                    pool=0, stride=0, first=1, last=0)
        ifm = [[[(0)] * 8 for _ in range(cfg.conv_col)] for _ in range(cfg.row)]
        for r in range(cfg.row):
            for c in range(cfg.conv_col):
                v = r * 16 + c
                for ch in range(8):
                    ifm[r][c][ch] = v
        w = make_identity_weights()
        bias = [0] * 8
    elif name == "probe2":
        cfg = Layer("probe2", sel=0, row=6, scale=0x7FFF, shift=0,
                    zp_in=0, zp_out=0, zp_act=0, relu_type=1,
                    pool=0, stride=0, first=1, last=0)
        ifm = [[[(8 + ch) for ch in range(8)] for _ in range(cfg.conv_col)]
               for _ in range(cfg.row)]
        w = make_identity_weights()
        bias = [0] * 8
    elif name == "A":
        cfg = Layer("A", sel=0, row=6, scale=0x7FFF, shift=0,
                    zp_in=0, zp_out=0, zp_act=0, relu_type=1,
                    pool=0, stride=0, first=1, last=0)
        ifm = [[[random.randint(-8, 7) for _ in range(8)]
                for _ in range(cfg.conv_col)] for _ in range(cfg.row)]
        w = [[[[random.randint(-4, 3) for _ in range(8)] for _ in range(9)]
              for _ in range(8)]]
        bias = [0] * 8
    elif name == "B":
        cfg = Layer("B", sel=0, row=6, scale=0x3A00, shift=3,
                    zp_in=5, zp_out=10, zp_act=0, relu_type=1,
                    pool=0, stride=0, first=1, last=1)
        ifm = [[[random.randint(-8, 7) for _ in range(8)]
                for _ in range(cfg.conv_col)] for _ in range(cfg.row)]
        w = [[[[random.randint(-4, 3) for _ in range(8)] for _ in range(9)]
              for _ in range(8)]]
        bias = [random.randint(-100, 100) for _ in range(8)]
    elif name == "C":
        cfg = Layer("C", sel=0, row=6, scale=0x2E00, shift=2,
                    zp_in=3, zp_out=7, zp_act=0, relu_type=0,
                    pool=0, stride=0, first=1, last=1)
        ifm = [[[random.randint(-8, 7) for _ in range(8)]
                for _ in range(cfg.conv_col)] for _ in range(cfg.row)]
        w = [[[[random.randint(-4, 3) for _ in range(8)] for _ in range(9)]
              for _ in range(8)]]
        bias = [random.randint(-100, 100) for _ in range(8)]
    else:
        raise SystemExit("unknown case: " + name)

    # Leaky LUT: deterministic permutation, makes the LUT path unmistakable.
    cfg.lut = [(i * 37 + 11) & 0xFF for i in range(256)]

    os.makedirs(outdir, exist_ok=True)
    ifm_words = pack_beats([[ifm[r][c][ch] for ch in range(8)]
                            for r in range(cfg.row)
                            for c in range(cfg.conv_col)])
    write_hex(os.path.join(outdir, "ifm.hex"), ifm_words)
    wbeats = []
    for og in range(cfg.out_groups):
        for ic in range(8):
            for tap in range(9):
                wbeats.append([w[og][ic][tap][oc] for oc in range(8)])
    wgt_words = pack_beats(wbeats)
    bia_words = [(bias[oc] & 0x3FFFF) for oc in range(8)]
    lut_words = [v for v in cfg.lut]
    write_hex(os.path.join(outdir, "wgt.hex"), wgt_words)
    write_hex(os.path.join(outdir, "bia.hex"), bia_words)
    write_hex(os.path.join(outdir, "lky.hex"), lut_words, width=8)

    gold = golden_conv(ifm, w, bias, cfg)
    gold_words = pack_beats(gold)
    words = cfg.ctrl_words(len(gold))
    write_hex(os.path.join(outdir, "ctrl.hex"), words, width=8)

    write_hex(os.path.join(outdir, "ofm_gold.hex"), gold_words)
    write_c_header(os.path.join(outdir, "vectors.h"), name, cfg, ifm_words,
                   wgt_words, bia_words, lut_words, gold_words)
    meta = {
        "name": name, "sel": cfg.sel, "row": cfg.row,
        "conv_col": cfg.conv_col, "valid_rows": cfg.row - 2,
        "valid_cols": cfg.conv_col - 2, "scale": cfg.scale,
        "shift": cfg.shift, "zp_in": cfg.zp_in, "zp_out": cfg.zp_out,
        "relu_type": cfg.relu_type, "pool": cfg.pool, "stride": cfg.stride,
        "ifm_beats": cfg.row * cfg.conv_col, "wgt_beats": len(wbeats),
        "gold_beats": len(gold),
    }
    with open(os.path.join(outdir, "meta.json"), "w") as f:
        json.dump(meta, f, indent=2)
    print("%-7s -> %s  (%d IFM beats, %d gold beats)" %
          (name, outdir, meta["ifm_beats"], len(gold)))


if __name__ == "__main__":
    case = sys.argv[1] if len(sys.argv) > 1 else "probe1"
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join("vec", case)
    build_case(case, out)